-- ---------------------------------------------------------------------
-- 0. LIMPEZA
-- Remove apenas as tabelas do Pharos, se existirem. Permite executar o
-- script de novo sem erro e sem apagar tabelas de outros trabalhos.
-- ---------------------------------------------------------------------
BEGIN
    FOR t IN (SELECT table_name
                FROM user_tables
               WHERE table_name IN ('PH_CONSULTA', 'PH_INDICADOR_OCORRENCIA',
                                    'PH_TIPO_OCORRENCIA', 'PH_ETAPA_TRAJETO',
                                    'PH_ALTERNATIVA', 'PH_PAR_ORIGEM_DESTINO',
                                    'PH_CENARIO', 'PH_LINHA', 'PH_PARADA',
                                    'PH_FONTE_DADOS')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/


-- ---------------------------------------------------------------------
-- 1. PH_FONTE_DADOS
-- Origem de cada informação exibida: dado oficial, dado calculado pela
-- equipe ou dado simulado. Permite mostrar ao usuário a fonte, o período
-- e as limitações dos dados.
-- ---------------------------------------------------------------------
CREATE TABLE ph_fonte_dados (
    id_fonte           NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    nm_fonte           VARCHAR2(120) NOT NULL,
    nm_orgao           VARCHAR2(120) NOT NULL,
    ds_versao          VARCHAR2(40),
    ds_url             VARCHAR2(300),
    dt_inicio_periodo  DATE,
    dt_fim_periodo     DATE,
    fl_simulado        CHAR(1)       DEFAULT 'N' NOT NULL,
    ds_limitacao       VARCHAR2(400) NOT NULL,
    CONSTRAINT pk_ph_fonte_dados    PRIMARY KEY (id_fonte),
    CONSTRAINT uk_ph_fonte_nome     UNIQUE (nm_fonte),
    CONSTRAINT ck_ph_fonte_simulado CHECK (fl_simulado IN ('S', 'N')),
    CONSTRAINT ck_ph_fonte_periodo  CHECK (dt_fim_periodo >= dt_inicio_periodo)
);


-- ---------------------------------------------------------------------
-- 2. PH_PARADA
-- Paradas e terminais da rede piloto (vértices do grafo usado no DP).
-- ---------------------------------------------------------------------
CREATE TABLE ph_parada (
    id_parada        NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    cd_parada_gtfs   VARCHAR2(20)  NOT NULL,
    nm_parada        VARCHAR2(150) NOT NULL,
    nm_municipio     VARCHAR2(60)  NOT NULL,
    nr_latitude      NUMBER(9,6),
    nr_longitude     NUMBER(9,6),
    fl_terminal      CHAR(1)       DEFAULT 'N' NOT NULL,
    fl_selecionavel  CHAR(1)       DEFAULT 'N' NOT NULL,
    id_fonte         NUMBER(10)    NOT NULL,
    CONSTRAINT pk_ph_parada          PRIMARY KEY (id_parada),
    CONSTRAINT uk_ph_parada_gtfs     UNIQUE (cd_parada_gtfs),
    CONSTRAINT ck_ph_parada_lat      CHECK (nr_latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_ph_parada_lon      CHECK (nr_longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_ph_parada_coord    CHECK ((nr_latitude IS NULL AND nr_longitude IS NULL)
                                         OR (nr_latitude IS NOT NULL AND nr_longitude IS NOT NULL)),
    CONSTRAINT ck_ph_parada_terminal CHECK (fl_terminal IN ('S', 'N')),
    CONSTRAINT ck_ph_parada_selec    CHECK (fl_selecionavel IN ('S', 'N'))
);


-- ---------------------------------------------------------------------
-- 3. PH_LINHA
-- Linhas de transporte público que aparecem na rede piloto.
-- ---------------------------------------------------------------------
CREATE TABLE ph_linha (
    id_linha       NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    cd_linha       VARCHAR2(20)  NOT NULL,
    ds_itinerario  VARCHAR2(300) NOT NULL,
    tp_modal       VARCHAR2(10)  DEFAULT 'ONIBUS' NOT NULL,
    id_fonte       NUMBER(10)    NOT NULL,
    CONSTRAINT pk_ph_linha        PRIMARY KEY (id_linha),
    CONSTRAINT uk_ph_linha_codigo UNIQUE (cd_linha),
    CONSTRAINT ck_ph_linha_modal  CHECK (tp_modal IN ('ONIBUS', 'METRO', 'TREM'))
);


-- ---------------------------------------------------------------------
-- 4. PH_CENARIO
-- Tipo de dia e janela de horário usados no cálculo das alternativas
-- (a espera e as linhas em operação mudam conforme o horário).
-- ---------------------------------------------------------------------
CREATE TABLE ph_cenario (
    id_cenario      NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    cd_cenario      VARCHAR2(20) NOT NULL,
    nm_cenario      VARCHAR2(80) NOT NULL,
    tp_dia          VARCHAR2(10) NOT NULL,
    nr_hora_inicio  NUMBER(2)    NOT NULL,
    nr_hora_fim     NUMBER(2)    NOT NULL,
    CONSTRAINT pk_ph_cenario          PRIMARY KEY (id_cenario),
    CONSTRAINT uk_ph_cenario_codigo   UNIQUE (cd_cenario),
    CONSTRAINT ck_ph_cenario_dia      CHECK (tp_dia IN ('UTIL', 'SABADO', 'DOMINGO')),
    CONSTRAINT ck_ph_cenario_hora_ini CHECK (nr_hora_inicio BETWEEN 0 AND 23),
    CONSTRAINT ck_ph_cenario_hora_fim CHECK (nr_hora_fim BETWEEN 1 AND 24),
    CONSTRAINT ck_ph_cenario_janela   CHECK (nr_hora_fim > nr_hora_inicio)
);


-- ---------------------------------------------------------------------
-- 5. PH_PAR_ORIGEM_DESTINO
-- Par origem-destino já calculado para um cenário. Quando não existe
-- trajeto, o par fica gravado com o status e sem alternativas, para a
-- API responder "sem trajeto" em vez de inventar um resultado.
-- ---------------------------------------------------------------------
CREATE TABLE ph_par_origem_destino (
    id_par_od          NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    id_cenario         NUMBER(10)   NOT NULL,
    id_parada_origem   NUMBER(10)   NOT NULL,
    id_parada_destino  NUMBER(10)   NOT NULL,
    st_resultado       VARCHAR2(25) NOT NULL,
    dt_calculo         DATE         DEFAULT SYSDATE NOT NULL,
    id_fonte           NUMBER(10)   NOT NULL,
    CONSTRAINT pk_ph_par_od         PRIMARY KEY (id_par_od),
    CONSTRAINT uk_ph_par_od         UNIQUE (id_cenario, id_parada_origem, id_parada_destino),
    CONSTRAINT ck_ph_par_od_paradas CHECK (id_parada_origem <> id_parada_destino),
    CONSTRAINT ck_ph_par_od_status  CHECK (st_resultado IN ('COM_ALTERNATIVAS', 'SEM_TRAJETO',
                                                            'SEM_TRAJETO_RAZOAVEL'))
);


-- ---------------------------------------------------------------------
-- 6. PH_ALTERNATIVA
-- Cada alternativa de deslocamento de um par, com os critérios que a
-- tela de comparação mostra lado a lado.
-- ---------------------------------------------------------------------
CREATE TABLE ph_alternativa (
    id_alternativa      NUMBER(10)  GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    id_par_od           NUMBER(10)  NOT NULL,
    nr_ordem            NUMBER(2)   NOT NULL,
    nr_tempo_total_min  NUMBER(5,1) NOT NULL,
    nr_distancia_km     NUMBER(6,2) NOT NULL,
    qt_baldeacoes       NUMBER(1)   NOT NULL,
    CONSTRAINT pk_ph_alternativa           PRIMARY KEY (id_alternativa),
    CONSTRAINT uk_ph_alternativa_ordem     UNIQUE (id_par_od, nr_ordem),
    CONSTRAINT ck_ph_alternativa_ordem     CHECK (nr_ordem >= 1),
    CONSTRAINT ck_ph_alternativa_tempo     CHECK (nr_tempo_total_min > 0),
    CONSTRAINT ck_ph_alternativa_dist      CHECK (nr_distancia_km > 0),
    CONSTRAINT ck_ph_alternativa_baldeacao CHECK (qt_baldeacoes BETWEEN 0 AND 2)
);


-- ---------------------------------------------------------------------
-- 7. PH_ETAPA_TRAJETO
-- Etapas de uma alternativa: em qual linha embarcar, onde embarcar e onde
-- descer. Resolve o relacionamento N:N entre ALTERNATIVA e LINHA.
-- Duas etapas seguidas na mesma parada representam uma baldeação.
-- ---------------------------------------------------------------------
CREATE TABLE ph_etapa_trajeto (
    id_etapa               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    id_alternativa         NUMBER(10) NOT NULL,
    nr_sequencia           NUMBER(2)  NOT NULL,
    id_linha               NUMBER(10) NOT NULL,
    id_parada_embarque     NUMBER(10) NOT NULL,
    id_parada_desembarque  NUMBER(10) NOT NULL,
    CONSTRAINT pk_ph_etapa_trajeto   PRIMARY KEY (id_etapa),
    CONSTRAINT uk_ph_etapa_sequencia UNIQUE (id_alternativa, nr_sequencia),
    CONSTRAINT ck_ph_etapa_sequencia CHECK (nr_sequencia >= 1),
    CONSTRAINT ck_ph_etapa_paradas   CHECK (id_parada_embarque <> id_parada_desembarque)
);


-- ---------------------------------------------------------------------
-- 8. PH_TIPO_OCORRENCIA
-- Categorias de ocorrência adotadas pela equipe para agrupar os registros
-- da SSP-SP.
-- ---------------------------------------------------------------------
CREATE TABLE ph_tipo_ocorrencia (
    id_tipo_ocorrencia  NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    cd_tipo             VARCHAR2(30)  NOT NULL,
    nm_tipo             VARCHAR2(80)  NOT NULL,
    ds_tipo             VARCHAR2(250),
    CONSTRAINT pk_ph_tipo_ocorrencia PRIMARY KEY (id_tipo_ocorrencia),
    CONSTRAINT uk_ph_tipo_codigo     UNIQUE (cd_tipo)
);


-- ---------------------------------------------------------------------
-- 9. PH_INDICADOR_OCORRENCIA
-- Contagem histórica de ocorrências registradas a até X metros do traçado
-- de uma alternativa, por tipo, ano e faixa horária. Só dado agregado.
-- ---------------------------------------------------------------------
CREATE TABLE ph_indicador_ocorrencia (
    id_indicador        NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    id_alternativa      NUMBER(10)   NOT NULL,
    id_tipo_ocorrencia  NUMBER(10)   NOT NULL,
    id_fonte            NUMBER(10)   NOT NULL,
    nr_ano              NUMBER(4)    NOT NULL,
    tp_faixa_horaria    VARCHAR2(10) NOT NULL,
    nr_raio_m           NUMBER(4)    NOT NULL,
    qt_ocorrencias      NUMBER(6)    NOT NULL,
    CONSTRAINT pk_ph_indicador         PRIMARY KEY (id_indicador),
    CONSTRAINT uk_ph_indicador_recorte UNIQUE (id_alternativa, id_tipo_ocorrencia, nr_ano,
                                               tp_faixa_horaria, nr_raio_m),
    CONSTRAINT ck_ph_indicador_ano     CHECK (nr_ano BETWEEN 2000 AND 2100),
    CONSTRAINT ck_ph_indicador_faixa   CHECK (tp_faixa_horaria IN ('MADRUGADA', 'MANHA', 'TARDE',
                                                                   'NOITE', 'INCERTA')),
    CONSTRAINT ck_ph_indicador_raio    CHECK (nr_raio_m IN (100, 250, 500)),
    CONSTRAINT ck_ph_indicador_qtd     CHECK (qt_ocorrencias >= 0)
);


-- ---------------------------------------------------------------------
-- 10. PH_CONSULTA
-- Registro anônimo de cada consulta feita na plataforma (sem login, sem
-- IP, sem dado pessoal). Alimenta os indicadores de impacto da Ficha:
-- tempo de resposta, alternativa escolhida e avaliação de utilidade.
-- ---------------------------------------------------------------------
CREATE TABLE ph_consulta (
    id_consulta               NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    id_par_od                 NUMBER(10)   NOT NULL,
    id_alternativa_escolhida  NUMBER(10),
    tp_criterio_ordenacao     VARCHAR2(15) NOT NULL,
    dt_consulta               TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    nr_tempo_resposta_ms      NUMBER(6),
    nr_avaliacao              NUMBER(1),
    fl_teste                  CHAR(1)      DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_ph_consulta            PRIMARY KEY (id_consulta),
    CONSTRAINT ck_ph_consulta_criterio   CHECK (tp_criterio_ordenacao IN ('TEMPO', 'DISTANCIA',
                                                                         'BALDEACOES', 'OCORRENCIAS')),
    CONSTRAINT ck_ph_consulta_tempo_resp CHECK (nr_tempo_resposta_ms >= 0),
    CONSTRAINT ck_ph_consulta_avaliacao  CHECK (nr_avaliacao BETWEEN 1 AND 5),
    CONSTRAINT ck_ph_consulta_teste      CHECK (fl_teste IN ('S', 'N'))
);


-- ---------------------------------------------------------------------
-- 11. CHAVES ESTRANGEIRAS (ALTER TABLE)
-- ON DELETE CASCADE só nas composições: alternativa pertence ao par,
-- etapa e indicador pertencem à alternativa. Nas demais, a exclusão do
-- registro pai é bloqueada enquanto houver filhos.
-- ---------------------------------------------------------------------
ALTER TABLE ph_parada ADD CONSTRAINT fk_ph_parada_fonte
    FOREIGN KEY (id_fonte) REFERENCES ph_fonte_dados (id_fonte);

ALTER TABLE ph_linha ADD CONSTRAINT fk_ph_linha_fonte
    FOREIGN KEY (id_fonte) REFERENCES ph_fonte_dados (id_fonte);

ALTER TABLE ph_par_origem_destino ADD CONSTRAINT fk_ph_par_od_cenario
    FOREIGN KEY (id_cenario) REFERENCES ph_cenario (id_cenario);

ALTER TABLE ph_par_origem_destino ADD CONSTRAINT fk_ph_par_od_origem
    FOREIGN KEY (id_parada_origem) REFERENCES ph_parada (id_parada);

ALTER TABLE ph_par_origem_destino ADD CONSTRAINT fk_ph_par_od_destino
    FOREIGN KEY (id_parada_destino) REFERENCES ph_parada (id_parada);

ALTER TABLE ph_par_origem_destino ADD CONSTRAINT fk_ph_par_od_fonte
    FOREIGN KEY (id_fonte) REFERENCES ph_fonte_dados (id_fonte);

ALTER TABLE ph_alternativa ADD CONSTRAINT fk_ph_alternativa_par_od
    FOREIGN KEY (id_par_od) REFERENCES ph_par_origem_destino (id_par_od) ON DELETE CASCADE;

ALTER TABLE ph_etapa_trajeto ADD CONSTRAINT fk_ph_etapa_alternativa
    FOREIGN KEY (id_alternativa) REFERENCES ph_alternativa (id_alternativa) ON DELETE CASCADE;

ALTER TABLE ph_etapa_trajeto ADD CONSTRAINT fk_ph_etapa_linha
    FOREIGN KEY (id_linha) REFERENCES ph_linha (id_linha);

ALTER TABLE ph_etapa_trajeto ADD CONSTRAINT fk_ph_etapa_embarque
    FOREIGN KEY (id_parada_embarque) REFERENCES ph_parada (id_parada);

ALTER TABLE ph_etapa_trajeto ADD CONSTRAINT fk_ph_etapa_desembarque
    FOREIGN KEY (id_parada_desembarque) REFERENCES ph_parada (id_parada);

ALTER TABLE ph_indicador_ocorrencia ADD CONSTRAINT fk_ph_indicador_alternativa
    FOREIGN KEY (id_alternativa) REFERENCES ph_alternativa (id_alternativa) ON DELETE CASCADE;

ALTER TABLE ph_indicador_ocorrencia ADD CONSTRAINT fk_ph_indicador_tipo
    FOREIGN KEY (id_tipo_ocorrencia) REFERENCES ph_tipo_ocorrencia (id_tipo_ocorrencia);

ALTER TABLE ph_indicador_ocorrencia ADD CONSTRAINT fk_ph_indicador_fonte
    FOREIGN KEY (id_fonte) REFERENCES ph_fonte_dados (id_fonte);

ALTER TABLE ph_consulta ADD CONSTRAINT fk_ph_consulta_par_od
    FOREIGN KEY (id_par_od) REFERENCES ph_par_origem_destino (id_par_od);

-- Se a alternativa escolhida for excluída, a consulta continua registrada
-- (para as métricas) e só perde a referência à escolha.
ALTER TABLE ph_consulta ADD CONSTRAINT fk_ph_consulta_alternativa
    FOREIGN KEY (id_alternativa_escolhida) REFERENCES ph_alternativa (id_alternativa) ON DELETE SET NULL;


-- ---------------------------------------------------------------------
-- 12. ÍNDICES nas chaves estrangeiras mais usadas pela API
-- (o Oracle não cria índice automático em FK).
-- ---------------------------------------------------------------------
CREATE INDEX ix_ph_par_od_origem   ON ph_par_origem_destino (id_parada_origem);
CREATE INDEX ix_ph_etapa_linha     ON ph_etapa_trajeto (id_linha);
CREATE INDEX ix_ph_consulta_par_od ON ph_consulta (id_par_od);


-- ---------------------------------------------------------------------
