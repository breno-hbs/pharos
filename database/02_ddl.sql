-- Modeler importa estes textos junto com o modelo).
-- ---------------------------------------------------------------------
COMMENT ON TABLE ph_fonte_dados IS 'Origem de cada dado: oficial, calculado pela equipe ou simulado';
COMMENT ON TABLE ph_parada IS 'Paradas e terminais da rede piloto (vértices do grafo)';
COMMENT ON TABLE ph_linha IS 'Linhas de transporte público da rede piloto';
COMMENT ON TABLE ph_cenario IS 'Tipo de dia e janela de horário usados no cálculo';
COMMENT ON TABLE ph_par_origem_destino IS 'Par origem-destino calculado para um cenário, com o status do cálculo';
COMMENT ON TABLE ph_alternativa IS 'Alternativa de deslocamento de um par origem-destino';
COMMENT ON TABLE ph_etapa_trajeto IS 'Etapa de uma alternativa: linha, parada de embarque e de desembarque';
COMMENT ON TABLE ph_tipo_ocorrencia IS 'Categoria de ocorrência criminal adotada pela equipe';
COMMENT ON TABLE ph_indicador_ocorrencia IS 'Contagem histórica agregada de ocorrências próximas ao traçado de uma alternativa';
COMMENT ON TABLE ph_consulta IS 'Registro anônimo das consultas feitas na plataforma';

COMMENT ON COLUMN ph_fonte_dados.fl_simulado IS 'S = dado simulado para testes; N = dado real ou calculado a partir de dado real';
COMMENT ON COLUMN ph_fonte_dados.ds_limitacao IS 'Limitações que a plataforma deve explicar ao usuário';
COMMENT ON COLUMN ph_parada.cd_parada_gtfs IS 'stop_id da parada no GTFS da ARTESP';
COMMENT ON COLUMN ph_parada.fl_selecionavel IS 'S = aparece como opção de origem/destino na tela';
COMMENT ON COLUMN ph_par_origem_destino.st_resultado IS 'COM_ALTERNATIVAS, SEM_TRAJETO ou SEM_TRAJETO_RAZOAVEL';
