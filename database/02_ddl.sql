COMMENT ON COLUMN ph_indicador_ocorrencia.nr_raio_m IS 'Distância máxima, em metros, entre a ocorrência e o traçado da alternativa';
COMMENT ON COLUMN ph_consulta.fl_teste IS 'S = consulta de teste, excluída das métricas de impacto';
