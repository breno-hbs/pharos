--    roda ANTES, em Python. O banco guarda o resultado: pares
--    origem-destino, alternativas e etapas. A API Java só consulta.
--  * Ocorrências criminais são guardadas apenas AGREGADAS (contagens).
--    Nenhum boletim individual e nenhum dado pessoal é armazenado.
--  * Chaves primárias numéricas geradas por IDENTITY a partir de 1000.
--    Os IDs de 1 a 999 ficam reservados para a carga inicial (03_dml.sql),
--    evitando colisão com registros criados depois pela API.
--  * As chaves estrangeiras são criadas com ALTER TABLE depois de todas
--    as tabelas, para não depender da ordem de criação.
